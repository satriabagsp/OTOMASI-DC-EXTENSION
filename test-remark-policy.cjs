const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const policy = require('./remark-policy.js');
const keys = ['gaji', 'biaya_produksi', 'biaya_pembelian', 'operasional', 'non_operasional', 'nilai_pendapatan', 'pendapatan_lain'];
const defs = keys.map(dataKey => ({dataKey, key: 'remark_' + dataKey}));
const old = Object.fromEntries(defs.map(r => [r.key, '#0']));
old.remark_operasional = '#3'; old.operasional = '220000';
const clean = policy.normalize(old, defs);
assert.equal(clean.remark_operasional, '#3');
assert.equal(defs.filter(r => clean[r.key]).length, 1);
assert.deepEqual(policy.validate(clean, defs), {});
const zero = policy.normalize(Object.fromEntries(defs.map(r => [r.key, '#DC_00'])), defs);
assert.equal(defs.filter(r => zero[r.key]).length, 1);
assert.ok(Object.keys(policy.validate({...zero, operasional: '220000'}, defs)).length);
assert.ok(policy.conflict([{dataKey:'gaji#1', comments:[{comment:'#0'}]}], '1', [{text:'#3'}]));
assert.equal(policy.conflict([{dataKey:'gaji#2', comments:[{comment:'#0'}]}], '1', [{text:'#3'}]), '');
let mod;
const context = { OTOMASI_DC_REMARK_POLICY: policy, OTOMASI_DC_BATCH: {register: m => {mod=m;}}, console };
vm.runInNewContext(fs.readFileSync('./custom/otomasi-dc-ntb.js', 'utf8'), context);
const answers = [{dataKey:'nama_usaha#1',answer:'TOKO'}, {dataKey:'tahun_operasi#1',answer:'2020'}, ...keys.map(k=>({dataKey:k+'#1',answer:'100'}))];
let notes=[]; let patches=0;
const fasih={getAssignment:async()=>({data:JSON.stringify({answers}),comment:JSON.stringify({notes}),code_identity:'test'}), patch:async()=>{patches++; return {};}};
(async()=>{
 notes=[{dataKey:'gaji#1',comments:[{comment:'#0'}]}];
 let result=await mod.process({assignment_id:'test',nama_usaha:'TOKO',operasional:'220000'},{dryRun:false,FASIH:fasih,remarks:[{dataKey:'operasional',text:'#3'}]});
 assert.equal(result.status,'PERLU_DATA'); assert.equal(patches,0);
 result=await mod.process({assignment_id:'test',nama_usaha:'TOKO'},{dryRun:false,FASIH:fasih,remarks:[{dataKey:'operasional',text:'#0'}]});
 assert.equal(result.status,'SELESAI'); assert.equal(patches,0);
 console.log('Pengujian aturan remark dan pemeriksaan sebelum perubahan: lulus.');
})().catch(e=>{console.error(e);process.exitCode=1;});
